#!/usr/bin/env node
/**
 * README.md's top and bottom are the welcome window's own words (user,
 * 2026-11-19, as Base Knavery's README): this writes the two blocks between
 * `<!-- welcome:start -->`/`<!-- welcome:end -->` and
 * `<!-- licensing:start -->`/`<!-- licensing:end -->` from lang/en.json
 * (CAIRN.Welcome.*) and module/welcome-data.js, so a change to the window is
 * made once. Everything between the blocks (Requirements & Installation, What
 * you get) is hand-written, and so is README.es.md, which mirrors it by hand.
 *
 * What only the window has stays out: the world's own background line (a
 * README has no world), the version (the release page has it), the buttons
 * that open compendiums, and the "show each time" box.
 *
 * Also holds the hand-written Requirements line to system.json's
 * compatibility.minimum, one of the places that state the minimum.
 *
 *   npm run build:readme      rewrite the two blocks
 *   npm run check:readme      fail if README.md is out of date with the window
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import process from "node:process";
import {
  AI_LINES, ART_CREDITS, BUY_LINKS, CC_BY_SA_URL, LICENCE_FOLDS, MARK_NAME, RULES, WELCOME_BOOKENDS, WELCOME_MARKS,
} from "../module/welcome-data.js";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => readFileSync(resolve(ROOT, p), "utf8");
const lang = JSON.parse(read("lang/en.json"));
const manifest = JSON.parse(read("system.json"));
const check = process.argv.includes("--check");

/**
 * A key from en.json, which nests some groups under a dotted top-level key
 * ("CAIRN.Welcome": {...}): try the longest dotted prefix that exists, then
 * walk the rest. {name} placeholders are filled from `data`.
 */
const L = (key, data = {}) => {
  const parts = key.split(".");
  let v;
  for (let i = parts.length; i > 0 && typeof v !== "string"; i--) {
    const head = lang[parts.slice(0, i).join(".")];
    v = parts.slice(i).reduce((o, k) => o?.[k], head);
  }
  if (typeof v !== "string") throw new Error(`build-readme: no string ${key}`);
  return v.replace(/\{(\w+)\}/g, (m, k) => (k in data ? data[k] : m));
};
const W = (k, data) => L(`CAIRN.Welcome.${k}`, data);
const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const a = (href, text) => `<a href="${href}">${text}</a>`;
const md = (href, text) => `[${text}](${href})`;

// The maintainer and the translator by name, as the window finds them.
const person = (name) => manifest.authors?.find((p) => p.name === name) ?? { name };
const author = person("Dom Bosco");
const translator = person("Malecho");
const NOTE = "generated by `npm run build:readme` from lang/en.json and module/welcome-data.js: edit those, not this";

// ---- the top: masthead, rules, books, AI disclosure -------------------------
const portrait = (src) => `<img src="${src}" alt="${esc(W("PortraitAlt"))}" height="100" align="middle">`;
const welcome = [
  `<!-- welcome:start (${NOTE}) -->`,
  `<h1 align="center">${portrait(WELCOME_BOOKENDS.left)} ${esc(MARK_NAME)}™ ${portrait(WELCOME_BOOKENDS.right)}</h1>`,
  `<p align="center">by ${a(author.url, esc(author.name))}<br>`
    + `${esc(W("Translation", { translator: "\u0000" })).replace("\u0000", a(translator.url, esc(translator.name)))}</p>`,
  "",
  `<p align="center"><b>English</b> · <a href="README.es.md">Español</a></p>`,
  "",
  `<p align="center"><em>${esc(W("Unofficial"))}<br>${esc(W("NotOfficial"))}</em></p>`,
  "",
  `## ${W("RulesHeading")}`,
  "",
  ...RULES.map(([title, body]) => `- **${L(title)}** ${L(body)}`),
  "",
  `## ${W("GetTheBooks")}`,
  "",
  W("Author"),
  "",
  `- **${W("Book")}**: ${BUY_LINKS.map((l) => md(l.href, L(l.label))).join(" · ")}`,
  "",
  W("BookNote"),
  "",
  `## ${W("AiHeading")}`,
  "",
  ...AI_LINES.map((l) => `- ${l.emoji} **${L(l.title)}**${l.body ? ` ${L(l.body)}` : ""}`),
  "",
  "<!-- welcome:end -->",
].join("\n");

// ---- the bottom: the licence folds, the origin line, the marks --------------
const fold = (summary, body) => `<details><summary><b>${esc(summary)}</b></summary>\n\n${body}\n\n</details>`;
const licenceLink = a(CC_BY_SA_URL, esc(W("CcBySa")));
const credit = (c) => {
  const name = c.nameKey ? L(c.nameKey) : c.name;
  const by = c.byKey ? L(c.byKey) : c.by;
  const lic = c.licenseKey ? L(c.licenseKey) : c.license;
  return `- ${md(c.url, name)}, ${by}: ${c.licenseUrl ? md(c.licenseUrl, lic) : lic}`;
};
const licensing = [
  `<!-- licensing:start (${NOTE}) -->`,
  `## ${W("Licensing")}`,
  "",
  ...LICENCE_FOLDS.map((f) => fold(L(f.heading), esc(L(f.body, { license: "\u0000" })).replace("\u0000", licenceLink))),
  fold(W("ArtLicensing"), ART_CREDITS.map(credit).join("\n")),
  "",
  "For more detail see [LICENSE.txt](LICENSE.txt).",
  "",
  `> ${W("Origin")}`,
  "",
  `<p align="right"><picture><source media="(prefers-color-scheme: dark)" srcset="${WELCOME_MARKS.logoDark}">`
    + `<img src="${WELCOME_MARKS.logo}" alt="${esc(MARK_NAME)}" width="150" align="middle"></picture> `
    + `<img src="${WELCOME_MARKS.stamp}" alt="${esc(W("StampAlt"))}" width="110" align="middle"></p>`,
  "",
  "<!-- licensing:end -->",
].join("\n");

// ---- write or check ---------------------------------------------------------
const between = (text, name, block) => {
  const re = new RegExp(`<!-- ${name}:start[^]*?<!-- ${name}:end -->`);
  if (!re.test(text)) throw new Error(`build-readme: README.md has no ${name}:start/end markers`);
  return text.replace(re, () => block);
};
// Line endings are compared away and kept as the file has them.
const lf = (t) => t.replace(/\r\n/g, "\n");
const file = read("README.md");
const readme = lf(file);
const next = between(between(readme, "welcome", welcome), "licensing", licensing);

const need = manifest.compatibility?.minimum;
const requires = `**Requires Foundry VTT v${need} or higher.**`;
if (!readme.includes(requires)) {
  console.error(`readme: the Requirements & Installation section must say ${requires} (system.json compatibility.minimum).`);
  process.exit(1);
}
if (check) {
  if (next !== readme) {
    console.error("readme: README.md is out of date with the welcome window. Run npm run build:readme.");
    process.exit(1);
  }
  console.log("readme: README.md matches the welcome window.");
} else {
  writeFileSync(resolve(ROOT, "README.md"), file.includes("\r\n") ? next.replace(/\n/g, "\r\n") : next);
  console.log(next === readme ? "readme: already up to date" : "readme: wrote README.md");
}
